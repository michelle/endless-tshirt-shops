export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Blank columns between glyphs, in font pixels. */
export const TRACKING = 2;

export function textWidth(text: string, scale: number): number {
  if (text.length === 0) return 0;
  return (text.length * (GLYPH_W + TRACKING) - TRACKING) * scale;
}

/** Blit `text` into an index buffer at (x, y), scaled by whole pixels. */
export function drawText(
  buf: Uint8Array,
  bufW: number,
  bufH: number,
  x: number,
  y: number,
  text: string,
  scale: number,
  colorIndex: number,
): void {
  let cursor = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[" "];
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const rowBits = glyph[gy];
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (rowBits[gx] !== "1") continue;
        const px0 = cursor + gx * scale;
        const py0 = y + gy * scale;
        for (let dy = 0; dy < scale; dy++) {
          const py = py0 + dy;
          if (py < 0 || py >= bufH) continue;
          const rowOff = py * bufW;
          for (let dx = 0; dx < scale; dx++) {
            const px = px0 + dx;
            if (px < 0 || px >= bufW) continue;
            buf[rowOff + px] = colorIndex;
          }
        }
      }
    }
    cursor += (GLYPH_W + TRACKING) * scale;
  }
}
