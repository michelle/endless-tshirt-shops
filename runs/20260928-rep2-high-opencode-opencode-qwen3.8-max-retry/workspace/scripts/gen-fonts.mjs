// Bundles the poster fonts as base64 so the artwork API never depends on
// filesystem tracing at deploy time. Regenerate with `npm run gen-fonts`.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const fontsDir = path.join(root, 'assets', 'fonts');
const out = path.join(root, 'lib', 'fonts-data.ts');

const names = {
  'cormorant-garamond-latin-400-normal.woff': 'CG_400',
  'cormorant-garamond-latin-500-normal.woff': 'CG_500',
  'cormorant-garamond-latin-600-normal.woff': 'CG_600',
  'cormorant-garamond-latin-400-italic.woff': 'CG_400_ITALIC',
  'inter-latin-400-normal.woff': 'INTER_400',
  'inter-latin-500-normal.woff': 'INTER_500',
  'inter-latin-600-normal.woff': 'INTER_600',
};

let body = '// Generated by scripts/gen-fonts.mjs — do not edit by hand.\n/* eslint-disable */\n';
for (const file of readdirSync(fontsDir).sort()) {
  const key = names[file];
  if (!key) continue;
  const b64 = readFileSync(path.join(fontsDir, file)).toString('base64');
  body += `export const ${key} = '${b64}';\n`;
}
body += `
function buf(b64: string): ArrayBuffer {
  const b = Buffer.from(b64, 'base64');
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength);
}

export const POSTER_FONTS = [
  { name: 'Cormorant Garamond', data: buf(CG_400), weight: 400 as const, style: 'normal' as const },
  { name: 'Cormorant Garamond', data: buf(CG_500), weight: 500 as const, style: 'normal' as const },
  { name: 'Cormorant Garamond', data: buf(CG_600), weight: 600 as const, style: 'normal' as const },
  { name: 'Cormorant Garamond', data: buf(CG_400_ITALIC), weight: 400 as const, style: 'italic' as const },
  { name: 'Inter', data: buf(INTER_400), weight: 400 as const, style: 'normal' as const },
  { name: 'Inter', data: buf(INTER_500), weight: 500 as const, style: 'normal' as const },
  { name: 'Inter', data: buf(INTER_600), weight: 600 as const, style: 'normal' as const },
];
`;
writeFileSync(out, body);
console.log(`wrote ${out} (${(body.length / 1024).toFixed(0)} KB)`);
