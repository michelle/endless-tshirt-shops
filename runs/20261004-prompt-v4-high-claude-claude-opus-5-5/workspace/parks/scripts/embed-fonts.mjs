// Embeds the TTFs as base64 so serverless bundles always include them.
import fs from "node:fs";
const fonts = { alfa: "fonts/AlfaSlabOne-Regular.ttf", anton: "fonts/Anton-Regular.ttf" };
let out = "// Generated by scripts/embed-fonts.mjs — do not edit.\n";
for (const [k, f] of Object.entries(fonts)) out += `export const ${k} = "${fs.readFileSync(f).toString("base64")}";\n`;
fs.writeFileSync("lib/fonts-data.ts", out);
