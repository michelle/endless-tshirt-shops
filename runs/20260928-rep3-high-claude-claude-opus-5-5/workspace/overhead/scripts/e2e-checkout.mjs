import { chromium } from "playwright";
const U = process.env.STORE_URL || "https://benchmark-20260928-rep3-high-claude.vercel.app";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 1000 } });
// Seed bag via designer deep link
await page.goto(U + "/design");
await page.getByLabel("Search for a place").fill("Portland");
await page.locator(".results button", { hasText: "Oregon" }).first().click();
await page.locator(".field", { hasText: "Title" }).locator("input").fill("Our First Home");
await page.getByRole("button", { name: "Add to bag" }).click();
await page.goto(U + "/bag");
await page.getByRole("button", { name: /check out/i }).click();
await page.waitForURL(/checkout\.stripe\.com/, { timeout: 30000 });
await page.waitForSelector("#email");
await page.fill("#email", "test.buyer@example.com");
await page.fill("#shippingName", "Test Buyer");
const manual = page.getByText("Enter address manually");
if (await manual.isVisible().catch(() => false)) await manual.click();
await page.selectOption("#shippingCountry", "US");
await page.fill("#shippingAddressLine1", "1234 SE Division St");
await page.keyboard.press("Escape");
await page.fill("#shippingLocality", "Portland");
await page.fill("#shippingPostalCode", "97202");
await page.selectOption("#shippingAdministrativeArea", "OR");
const phone = page.locator("#phoneNumber");
if (await phone.count()) await phone.fill("5035550123");
await page.locator("#payment-method-label-card").click({ force: true });
await page.waitForSelector("#cardNumber");
await page.fill("#cardNumber", "4242424242424242");
await page.fill("#cardExpiry", "12/34");
await page.fill("#cardCvc", "123");
const bn = page.locator("#billingName"); if (await bn.count() && await bn.isVisible()) await bn.fill("Test Buyer");
const save = page.locator("#enableStripePass"); if (await save.count() && await save.isChecked()) await save.uncheck().catch(()=>{});
await page.locator('button[type="submit"], [data-testid="hosted-payment-submit-button"]').first().click();
await page.waitForURL(/\/order\/cs_test_/, { timeout: 60000 });
console.log("ORDER URL", page.url());
await page.waitForSelector(".status-track", { timeout: 60000 });
await page.screenshot({ path: "06-order.png", fullPage: true });
await browser.close();
