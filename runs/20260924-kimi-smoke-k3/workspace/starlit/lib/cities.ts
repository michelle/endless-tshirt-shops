export function searchCities(q: string, limit = 8) {
  const needle = q.trim().toLowerCase();
  if (!needle) return [];
  return CITIES.filter(
    ([name, country]) =>
      name.toLowerCase().includes(needle) || country.toLowerCase().includes(needle)
  )
    .slice(0, limit)
    .map(([name, country, lat, lng]) => ({
      label: `${name}, ${country}`,
      lat,
      lng,
    }));
}
