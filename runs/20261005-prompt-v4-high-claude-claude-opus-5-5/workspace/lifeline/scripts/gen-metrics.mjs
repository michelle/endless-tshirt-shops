// Generates public/metrics.js: per-character advance widths (in 1/1000 em) for the
// Inter Display weights we print with. Used by design.js to measure and fit text
// identically in the browser preview and in the server-side print render.
import * as fontkit from 'fontkit';
import { writeFileSync } from 'node:fs';

const RANGES = [
  [0x20, 0x7e], [0xa0, 0x24f],      // Latin, Latin-1, Latin Extended-A/B
  [0x370, 0x3ff], [0x400, 0x4ff],   // Greek, Cyrillic
  [0x2010, 0x2027], [0x2030, 0x203a], [0x20ac, 0x20ac], [0x2116, 0x2116], [0x2122, 0x2122],
  [0x2190, 0x2195], [0x21c4, 0x21c6], [0x2192, 0x2192], [0x2605, 0x2606], [0x2665, 0x2665],
];

const out = {};
for (const [key, file] of [['medium', 'Medium'], ['bold', 'Bold'], ['black', 'Black']]) {
  const font = fontkit.openSync(`fonts/InterDisplay-${file}.ttf`);
  const map = {};
  for (const [a, b] of RANGES) {
    for (let cp = a; cp <= b; cp++) {
      if (!font.hasGlyphForCodePoint(cp)) continue;
      const g = font.glyphForCodePoint(cp);
      map[String.fromCodePoint(cp)] = Math.round((g.advanceWidth / font.unitsPerEm) * 1000);
    }
  }
  out[key] = map;
}

writeFileSync(
  'public/metrics.js',
  '// Generated by scripts/gen-metrics.mjs — do not edit by hand.\n' +
    `export const METRICS = ${JSON.stringify(out)};\n`
);
console.log('chars per weight:', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Object.keys(v).length])));
