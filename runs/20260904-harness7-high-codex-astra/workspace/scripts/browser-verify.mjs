const health=await (await fetch(process.env.APP_URL+'/api/health')).json();if(health.mode!=='sandbox')throw new Error('This verification script is sandbox-only');
import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.APP_URL,{waitUntil:'networkidle'});
fs.mkdirSync('artifacts',{recursive:true});
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
console.log('Title:',await page.title());
await page.getByRole('button',{name:'Size guide'}).click();
await page.getByRole('button',{name:'Got it'}).click();
await page.getByRole('button',{name:'Fitted',exact:true}).click();
await page.getByRole('button',{name:'L',exact:true}).click();
await page.getByRole('button',{name:'Capture this moment',exact:true}).click();
const timestamp=await page.locator('.captured-number').innerText();
console.log('Captured',timestamp);
await page.screenshot({path:'artifacts/review.png'});
await page.getByRole('button',{name:'Continue to checkout'}).click();
await page.waitForURL('https://checkout.stripe.com/**',{timeout:60000});
await page.waitForLoadState('domcontentloaded');
await page.screenshot({path:'artifacts/stripe-checkout.png',fullPage:true});
console.log('Checkout URL',page.url());
console.log((await page.locator('body').innerText()).slice(0,10000));
console.log('Input fields',await page.locator('input,select').evaluateAll(el=>el.map(x=>({tag:x.tagName,id:x.id,name:x.name,type:x.type,placeholder:x.placeholder}))));
fs.writeFileSync('artifacts/checkout-url.txt',page.url());
console.log('Errors',errors);
await browser.close();
