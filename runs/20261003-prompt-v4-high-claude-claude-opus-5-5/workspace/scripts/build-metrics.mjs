// Generates public/js/metrics.js: per-font advance widths (in em) for every
// character the store accepts, so browser preview and server print layout match.
import opentype from 'opentype.js';
import { writeFileSync, readFileSync } from 'node:fs';

const FONTS = {
  title: 'BarlowCondensed-ExtraBold',
  cond: 'BarlowCondensed-Bold',
  bold: 'Barlow-Bold',
  semi: 'Barlow-SemiBold',
  medium: 'Barlow-Medium',
};
const ranges = [[0x20, 0x7e], [0xa0, 0x17f]];
const extras = '–—‘’“”•·…€★♥';

const chars = [];
for (const [a, b] of ranges) for (let c = a; c <= b; c++) chars.push(String.fromCodePoint(c));
chars.push(...extras);

const out = {};
let supported = null;
for (const [key, file] of Object.entries(FONTS)) {
  const font = opentype.parse(readFileSync(`public/fonts/${file}.ttf`).buffer);
  const ok = chars.filter((ch) => font.charToGlyphIndex(ch) > 0 || ch === ' ');
  supported = supported ? supported.filter((c) => ok.includes(c)) : ok;
  const widths = {};
  for (const ch of ok) widths[ch] = +(font.charToGlyph(ch).advanceWidth / font.unitsPerEm).toFixed(4);
  out[key] = widths;
}
for (const key of Object.keys(out)) {
  out[key] = Object.fromEntries(supported.map((c) => [c, out[key][c]]));
}
writeFileSync(
  'public/js/metrics.js',
  `// Generated by scripts/build-metrics.mjs — do not edit.\nexport const SUPPORTED = ${JSON.stringify(supported.join(''))};\nexport const METRICS = ${JSON.stringify(out)};\n`,
);
console.log(`${supported.length} supported chars; missing:`, chars.filter((c) => !supported.includes(c)).join(''));
