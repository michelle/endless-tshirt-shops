import { chromium } from "playwright";
const U = process.env.U;
const shots = "shots";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text()); });
const step = async (name, fn) => { try { await fn(); console.log("ok:", name); } catch (e) { console.log("FAIL:", name, e.message); await page.screenshot({ path: `${shots}/fail-${name}.png`, fullPage: true }); throw e; } };

await step("home", async () => { await page.goto(U + "/"); await page.waitForTimeout(800); await page.screenshot({ path: `${shots}/home.png`, fullPage: true }); });
await step("design", async () => {
  await page.goto(U + "/design");
  await page.waitForTimeout(500);
  await page.getByPlaceholder("e.g. Maria, Biscuit").fill("Ada");
  await page.getByPlaceholder("Kitchen, near the snacks").fill("Server room, row 3");
  await page.getByPlaceholder("Iced coffee & gossip").fill("Punch cards & tea");
  await page.getByPlaceholder("Wait, what?").fill("Have you tried turning it off?");
  await page.getByRole("button", { name: "Beetle" }).click();
  await page.getByRole("button", { name: "Navy" }).click();
  await page.locator("select").nth(1).selectOption("l");
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${shots}/design.png`, fullPage: false });
  await page.getByRole("button", { name: "Print file" }).click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${shots}/design-plate.png` });
  await page.getByRole("button", { name: "Add to bag" }).click();
  await page.getByText("Specimen added to your bag.").waitFor();
});
await step("cart", async () => {
  await page.goto(U + "/cart");
  await page.getByRole("button", { name: "Checkout securely" }).waitFor();
  await page.screenshot({ path: `${shots}/cart.png`, fullPage: true });
  await page.getByRole("button", { name: "Checkout securely" }).click();
  await page.waitForURL(/checkout\.stripe\.com/, { timeout: 30000 });
});
await step("stripe", async () => {
  await page.waitForLoadState("networkidle");
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${shots}/stripe-0.png`, fullPage: true });
  await page.locator("#email").fill("e2e-test@example.com");
  const manual = page.getByText(/enter address manually/i);
  if (await manual.count()) await manual.first().click();
  await page.locator("#shippingName").fill("Ada Lovelace");
  const country = page.locator("#shippingCountry");
  if (await country.count()) await country.selectOption("US");
  await page.locator("#shippingAddressLine1").fill("350 Fifth Avenue");
  await page.keyboard.press("Escape");
  await page.locator("#shippingLocality").fill("New York");
  await page.locator("#shippingPostalCode").fill("10118");
  const st = page.locator("#shippingAdministrativeArea");
  if (await st.count()) await st.selectOption("NY");
  const phone = page.locator("#phoneNumber");
  if (await phone.count()) await phone.fill("2125550123");
  await page.waitForTimeout(1500);
  const cardRadio = page.locator('[data-testid="card-accordion-item-button"]');
  await cardRadio.dispatchEvent("click");
  await page.locator("#cardNumber").waitFor({ timeout: 15000 });
  await page.locator("#cardNumber").fill("4242424242424242");
  await page.locator("#cardExpiry").fill("12 / 34");
  await page.locator("#cardCvc").fill("123");
  const bn = page.locator("#billingName");
  if (await bn.count() && await bn.isVisible()) await bn.fill("Ada Lovelace");
  const save = page.getByRole("checkbox", { name: /save my information/i });
  if (await save.count() && await save.isChecked()) await save.uncheck({ force: true });
  await page.screenshot({ path: `${shots}/stripe-1.png`, fullPage: true });
  await page.locator('[data-testid="hosted-payment-submit-button"]').click();
  await page.waitForURL(/\/order\?session_id=/, { timeout: 60000 });
});
await step("order", async () => {
  console.log("order url:", page.url());
  await page.getByText("Payment received").waitFor({ timeout: 30000 });
  await page.screenshot({ path: `${shots}/order-0.png`, fullPage: true });
  await page.getByText("Print files sent to the lab").waitFor({ timeout: 90000 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${shots}/order-1.png`, fullPage: true });
  console.log(await page.locator(".timeline").innerText());
});
await browser.close();
